#!/usr/bin/env node
'use strict';
// Builds styles.css, the plugin's stylesheet, from its sources:
//   src/plugin.css               the plugin's own styles (sheet shadows, page labels, settings page)
//   snippets/lined-paper.css     the paper, rows, title bar, A4 pages, PDF export
//   snippets/cornell-notes.css   the Cornell layout
// so one install gives everything. The snippets stay usable on their own (without the plugin).
// An @import is only valid at the very top of a stylesheet, so they are moved there.
//   node scripts/build.js           write styles.css
//   node scripts/build.js --check   fail if styles.css is out of date (used by `npm run lint`)
const fs = require('node:fs');
const path = require('node:path');

const ROOT = path.resolve(__dirname, '..');
const SOURCES = ['src/plugin.css', 'snippets/lined-paper.css', 'snippets/cornell-notes.css'];
const IMPORT = /^@import\s+url\([^)]*\)[^;]*;[ \t]*\n?/gm;

function build() {
  const imports = [];
  const parts = SOURCES.map((file) => {
    const css = fs.readFileSync(path.join(ROOT, file), 'utf8').replace(IMPORT, (m) => { imports.push(m.trim()); return ''; });
    return `/* ==== ${file} ${'='.repeat(Math.max(4, 88 - file.length))} */\n\n${css.trim()}\n`;
  });
  return [
    '/* Lined Paper Pages: the plugin\'s stylesheet. GENERATED by scripts/build.js from',
    `   ${SOURCES.join(', ')}.`,
    '   Edit those files, then run `npm run build`. */',
    '',
    ...imports,
    '',
    parts.join('\n'),
  ].join('\n');
}

const out = path.join(ROOT, 'styles.css');
const css = build();
if (process.argv.includes('--check')) {
  const current = fs.existsSync(out) ? fs.readFileSync(out, 'utf8') : '';
  if (current !== css) {
    console.error('✖ styles.css is out of date: run `npm run build`');
    process.exit(1);
  }
  console.log('✔ styles.css is up to date');
} else {
  fs.writeFileSync(out, css);
  console.log(`styles.css (${(css.length / 1024).toFixed(0)} KB from ${SOURCES.length} files)`);
}
